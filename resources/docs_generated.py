"""Generated documentation pages shared by the GitHub wiki and the dashboard ``/docs`` UI.

The wiki build (``scripts/wiki_sync.py``) and the daemon (``resources/daemon/docs_ui.py``) both render
the "Mise-Tasks" and "API-Reference" pages from here so the two never drift. Pure functions only.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OPENAPI_SOURCE = "docs/openapi.yaml"
_MISE_HEADER_RE = re.compile(r"^#MISE\s+(description|aliases)\s*=\s*(.+)$")
_HTTP_METHODS = ("get", "post", "put", "patch", "delete", "head", "options")


@dataclass
class Task:
  name: str
  aliases: list[str]
  description: str


def _generated_note(source: str) -> str:
  return "<!-- Generated by `mise run wiki:build` from %s. Edit the source in the main repository, not this page. -->" % source


def mise_tasks(root: Path = ROOT) -> list[Task]:
  """Tasks defined under ``.mise/tasks`` with their ``#MISE`` description and aliases."""
  tasks_dir = root / ".mise" / "tasks"
  tasks = []
  for path in sorted(tasks_dir.rglob("*")):
    if not path.is_file() or path.name.startswith("."):
      continue
    description, aliases = "", []
    with open(path, encoding="utf-8", errors="replace") as f:
      for _ in range(10):
        line = f.readline()
        if not line:
          break
        match = _MISE_HEADER_RE.match(line.strip())
        if not match:
          continue
        key, value = match.groups()
        try:
          parsed = json.loads(value)
        except ValueError:
          parsed = value.strip("\"'")
        if key == "description":
          description = str(parsed)
        else:
          aliases = [str(a) for a in parsed] if isinstance(parsed, list) else [str(parsed)]
    if not description:
      continue
    parts = path.relative_to(tasks_dir).parts
    if parts[-1] == "_default":  # mise names <group>/_default as the bare group task
      parts = parts[:-1]
    name = ":".join(parts)
    tasks.append(Task(name, aliases, description))
  return tasks


def task_names(root: Path = ROOT) -> set[str]:
  """Every runnable task name and alias."""
  names = set()
  for task in mise_tasks(root):
    names.add(task.name)
    names.update(task.aliases)
  return names


def _cell(text: str) -> str:
  return text.replace("|", "\\|")


def render_mise_tasks(tasks: list[Task]) -> str:
  lines = [
    _generated_note(".mise/tasks/"),
    "",
    "# Mise Tasks",
    "",
    "All `mise run` tasks in the project, generated from each task's `#MISE description`.",
    "Run `mise tasks` to list them locally.",
    "",
    "Install [mise](https://mise.jdx.dev/) with `curl https://mise.run | sh`, then run `mise install` once in the",
    "repository root to activate the pinned tools.",
  ]
  groups: dict[str, list[Task]] = {}
  for task in tasks:
    groups.setdefault(task.name.split(":", 1)[0], []).append(task)
  for group in sorted(groups):
    lines += ["", "## %s" % group, "", "| Task | Aliases | Description |", "| --- | --- | --- |"]
    for task in groups[group]:
      aliases = ", ".join("`%s`" % a for a in task.aliases)
      lines.append("| `mise run %s` | %s | %s |" % (task.name, aliases, _cell(task.description)))
  return "\n".join(lines) + "\n"


def render_api_reference(spec: str) -> str:
  return "\n".join(
    [
      _generated_note(OPENAPI_SOURCE),
      "",
      "# API Reference",
      "",
      "The SMA-NG daemon's OpenAPI 3.1 specification. The endpoints, authentication and request formats are",
      "described in [Daemon Mode](Daemon-Mode); a running daemon also serves its own docs at `/docs`.",
      "",
      "```yaml",
      spec.rstrip("\n"),
      "```",
      "",
    ]
  )


def _schema_name(schema) -> str:
  if not isinstance(schema, dict):
    return ""
  if "$ref" in schema:
    return str(schema["$ref"]).rsplit("/", 1)[-1]
  return str(schema.get("type", ""))


def _oneline(text) -> str:
  return _cell(" ".join(str(text or "").split()))


def _auth_label(operation: dict, default_security: list) -> str:
  security = operation.get("security", default_security) or []
  if not security:
    return "none"
  if any(not req for req in security):
    return "optional (API key or bearer token)"
  return "API key or bearer token"


def render_api_endpoints(spec_text: str) -> str:
  """Readable markdown for an OpenAPI document: endpoints grouped by tag with auth, parameters and responses."""
  spec = yaml.safe_load(spec_text) or {}
  info = spec.get("info", {})
  default_security = spec.get("security", [])
  groups: dict[str, list[tuple[str, str, dict]]] = {}
  for path, item in (spec.get("paths") or {}).items():
    for method in _HTTP_METHODS:
      op = (item or {}).get(method)
      if isinstance(op, dict):
        groups.setdefault((op.get("tags") or ["other"])[0], []).append((method.upper(), path, op))
  lines = ["# API Reference", ""]
  if info.get("description"):
    lines += [" ".join(str(info["description"]).split()), ""]
  lines += ["Generated from the daemon's OpenAPI specification (`%s`)." % OPENAPI_SOURCE, ""]
  for tag in sorted(groups):
    lines += ["## %s" % tag, ""]
    for method, path, op in groups[tag]:
      lines += ["### %s %s" % (method, path), ""]
      if op.get("summary"):
        lines += [_oneline(op["summary"]), ""]
      if op.get("description"):
        lines += [_oneline(op["description"]), ""]
      lines += ["Auth: %s" % _auth_label(op, default_security), ""]
      params = [p for p in (op.get("parameters") or []) if isinstance(p, dict) and "name" in p]
      if params:
        lines += ["| Parameter | In | Type | Required | Description |", "| --- | --- | --- | --- | --- |"]
        for p in params:
          lines.append("| `%s` | %s | %s | %s | %s |" % (p["name"], p.get("in", ""), _schema_name(p.get("schema")), "yes" if p.get("required") else "no", _oneline(p.get("description"))))
        lines.append("")
      body = (op.get("requestBody") or {}).get("content") or {}
      if body:
        lines += ["Request body: " + ", ".join("`%s` (%s)" % (ctype, _schema_name(c.get("schema")) or "any") for ctype, c in body.items()), ""]
      responses = op.get("responses") or {}
      if responses:
        lines += ["| Status | Description |", "| --- | --- |"]
        lines += ["| %s | %s |" % (code, _oneline((r or {}).get("description"))) for code, r in responses.items()]
        lines.append("")
  return "\n".join(lines).rstrip("\n") + "\n"
