import pytest

SCRIPTS = Path(__file__).resolve().parent.parent / "scripts"
sys.path.insert(0, str(SCRIPTS))

import check_docs  # noqa: E402
import wiki_sync  # noqa: E402

SLUG = "owner/repo"


def _write(root, rel, text):
  path = root / rel
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(text, encoding="utf-8")
  return path


@pytest.fixture
def repo(tmp_path):
  """Minimal repository: every PAGES source, openapi.yaml, a logo, and two mise tasks."""
  for source, page, _ in wiki_sync.PAGES:
    _write(tmp_path, source, "# %s\n" % page)
  _write(tmp_path, "docs/openapi.yaml", "openapi: 3.1.0\ninfo:\n  title: Test\n")
  _write(tmp_path, "logo.png", "png")
  _write(tmp_path, "setup/sma-host.sh", "#!/bin/sh\n")
  _write(tmp_path, ".mise/tasks/wiki/build", '#!/usr/bin/env bash\n#MISE description="Build the wiki | pages"\nset -e\n')
  _write(tmp_path, ".mise/tasks/test/run", '#!/usr/bin/env bash\n#MISE description="Run tests"\n#MISE aliases=["test"]\n')
  _write(tmp_path, ".mise/tasks/test/undocumented", "#!/usr/bin/env bash\necho hi\n")
  return tmp_path


class TestRewriteLinks:
  def test_mapped_docs_become_wiki_pages_with_anchors(self, repo):
    text = "See [config](configuration.md#profiles) and [daemon](daemon.md)."
    out = wiki_sync.rewrite_links(text, "docs/README.md", SLUG, repo)
    assert out == "See [config](Configuration#profiles) and [daemon](Daemon-Mode)."

  def test_openapi_link_becomes_api_reference(self, repo):
    out = wiki_sync.rewrite_links("[spec](openapi.yaml)", "docs/daemon.md", SLUG, repo)
    assert out == "[spec](API-Reference)"

  def test_repo_files_become_github_urls_and_images_raw(self, repo):
    text = "![logo](../logo.png) [host](../setup/sma-host.sh#L1) [setup](../setup/)"
    out = wiki_sync.rewrite_links(text, "docs/README.md", SLUG, repo)
    assert "![logo](https://raw.githubusercontent.com/owner/repo/main/logo.png)" in out
    assert "[host](https://github.com/owner/repo/blob/main/setup/sma-host.sh#L1)" in out
    assert "[setup](https://github.com/owner/repo/tree/main/setup)" in out

  def test_external_and_anchor_links_untouched(self, repo):
    text = "[web](https://example.com/a.md) [here](#section) [mail](mailto:a@b.c)"
    assert wiki_sync.rewrite_links(text, "docs/README.md", SLUG, repo) == text

  def test_code_fences_untouched(self, repo):
    text = "```markdown\n[config](configuration.md)\n```\n[config](configuration.md)"
    out = wiki_sync.rewrite_links(text, "docs/README.md", SLUG, repo)
    assert out == "```markdown\n[config](configuration.md)\n```\n[config](Configuration)"

  def test_unresolved_links_reported_and_left_alone(self, repo):
    unresolved = []
    out = wiki_sync.rewrite_links("[gone](missing.md)", "docs/README.md", SLUG, repo, unresolved=unresolved)
    assert out == "[gone](missing.md)"
    assert unresolved == ["docs/README.md: missing.md"]


class TestMiseTasks:
  def test_parses_description_and_aliases_and_skips_undescribed(self, repo):
    tasks = wiki_sync.mise_tasks(repo)
    assert [(t.name, t.aliases, t.description) for t in tasks] == [
      ("test:run", ["test"], "Run tests"),
      ("wiki:build", [], "Build the wiki | pages"),
    ]
    assert wiki_sync.task_names(repo) == {"test:run", "test", "wiki:build"}

  def test_rendered_table_escapes_pipes(self, repo):
    page = wiki_sync.render_mise_tasks(wiki_sync.mise_tasks(repo))
    assert "| `mise run wiki:build` |  | Build the wiki \\| pages |" in page
    assert "| `mise run test:run` | `test` | Run tests |" in page

  def test_real_repo_tasks_all_have_descriptions(self):
    names = wiki_sync.task_names()
    assert {"wiki:build", "wiki:publish", "docs:check", "release:status", "release:notes", "deps:outdated"} <= names


class TestBuild:
  def test_build_writes_every_page_with_generated_note(self, repo):
    out = repo / "wiki"
    (out).mkdir()
    (out / "Old-Page.md").write_text("stale")
    wiki_sync.build(out, root=repo)
    names = sorted(p.name for p in out.glob("*.md"))
    expected = sorted([page + ".md" for _, page, _ in wiki_sync.PAGES] + ["API-Reference.md", "Mise-Tasks.md", "_Sidebar.md", "_Footer.md", "Old-Page.md"])
    assert names == expected
    assert (out / "Home.md").read_text().startswith("<!-- Generated by `mise run wiki:build` from docs/README.md.")
    api = (out / "API-Reference.md").read_text()
    assert "```yaml\nopenapi: 3.1.0" in api

  def test_prune_removes_unmanaged_pages(self, repo):
    out = repo / "wiki"
    out.mkdir()
    (out / "Old-Page.md").write_text("stale")
    wiki_sync.build(out, root=repo, prune=True)
    assert not (out / "Old-Page.md").exists()

  def test_sidebar_lists_every_page_once(self):
    sidebar = wiki_sync.render_sidebar()
    for _, page, section in wiki_sync.PAGES:
      if section:
        assert sidebar.count("](%s)" % page) == 1
    assert "](Mise-Tasks)" in sidebar and "](API-Reference)" in sidebar


class TestCheck:
  def test_real_repo_passes(self, capsys):
    assert wiki_sync.check() == 0
    assert "all links resolve" in capsys.readouterr().out

  def test_unmapped_doc_and_broken_link_fail(self, repo, capsys):
    _write(repo, "docs/new-topic.md", "# New\n")
    _write(repo, "docs/configuration.md", "[x](nowhere.md)\n")
    assert wiki_sync.check(root=repo) == 1
    err = capsys.readouterr().err
    assert "no wiki page mapping for docs/new-topic.md" in err
    assert "unresolved link docs/configuration.md: nowhere.md" in err

  def test_repo_slug_parses_https_and_ssh(self, tmp_path, monkeypatch):
    class Done:
      def __init__(self, url):
        self.stdout = url

    for url in ("https://github.com/a/b.git", "git@github.com:a/b.git", "https://github.com/a/b"):
      monkeypatch.setattr(wiki_sync.subprocess, "run", lambda *a, url=url, **k: Done(url))
      assert wiki_sync.repo_slug(tmp_path) == "a/b"


class TestCheckDocs:
  def test_real_repo_passes(self):
    assert check_docs.main() == 0

  @pytest.mark.parametrize(
    "line,ok",
    [
      ("mise run test:run", True),
      ("mise run test", True),
      ("mise run test:*", True),
      ("mise run test:{run}", True),
      ("mise run test:{run,missing}", False),
      ("mise run dev:check", False),
      ("mise run nope:*", False),
    ],
  )
  def test_mise_references(self, repo, line, ok):
    path = _write(repo, "docs/x.md", "%s\n" % line)
    problems = check_docs.check_file(path, repo, wiki_sync.task_names(repo))
    assert (problems == []) is ok

  def test_broken_link_outside_fence_only(self, repo):
    path = _write(repo, "docs/x.md", "```text\n[a](gone.md)\n```\n[b](gone.md)\n[c](configuration.md)\n")
    problems = check_docs.check_file(path, repo, set())
    assert problems == ["docs/x.md:4: broken link gone.md"]

  def test_doc_files_cover_root_and_docs(self):
    names = {os.path.relpath(p, check_docs.ROOT) for p in check_docs.doc_files()}
    assert {"README.md", "CONTRIBUTING.md", "docs/configuration.md"} <= names
