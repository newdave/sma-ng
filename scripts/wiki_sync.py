#!/usr/bin/env python3
"""Generate the GitHub wiki from ``docs/``.

The wiki (``<repo>.wiki.git``) is a rendered copy of the canonical docs, not a
second source: every page is regenerated from the repository so the two never
drift. ``mise run wiki:build`` / ``wiki:publish`` drive this script.

Pages:

- ``docs/<slug>.md`` -> the wiki page named in ``PAGES`` (``README.md`` -> ``Home``).
- ``docs/openapi.yaml`` -> ``API-Reference`` (the spec in a fenced YAML block).
- ``.mise/tasks/**`` ``#MISE description=`` headers -> ``Mise-Tasks``.
- ``_Sidebar`` and ``_Footer`` are generated from ``PAGES``.

Links are rewritten for the wiki: links to mapped docs become wiki page links
(``configuration.md#x`` -> ``Configuration#x``); other repository paths become
GitHub URLs (raw URLs for images). Fenced code blocks are left untouched.

Usage:
    python scripts/wiki_sync.py build --out /tmp/sma-wiki [--prune]
    python scripts/wiki_sync.py check
"""

from __future__ import annotations

import argparse
import json
import os
import posixpath
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SLUG = "newdave/sma-ng"
DEFAULT_REF = "main"

# (source path relative to the repo root, wiki page name, sidebar section)
PAGES: list[tuple[str, str, str]] = [
  ("docs/README.md", "Home", ""),
  ("docs/getting-started.md", "Getting-Started", "User Guide"),
  ("docs/docker-compose-quickstart.md", "Docker-Compose-Quick-Start", "User Guide"),
  ("docs/configuration.md", "Configuration", "User Guide"),
  ("docs/integrations.md", "Integrations", "User Guide"),
  ("docs/library-audit.md", "Library-Audit", "User Guide"),
  ("docs/daemon.md", "Daemon-Mode", "Running the Daemon"),
  ("docs/cluster-operations.md", "Cluster-Operations", "Running the Daemon"),
  ("docs/metrics.md", "Cluster-Metrics", "Running the Daemon"),
  ("docs/hardware-acceleration.md", "Hardware-Acceleration", "Running the Daemon"),
  ("docs/deployment.md", "Deployment", "Running the Daemon"),
  ("docs/multi-instance-deployment.md", "Multi-Instance-Deployment", "Running the Daemon"),
  ("docs/environment-architecture.md", "Environment-Architecture", "Running the Daemon"),
  ("docs/troubleshooting.md", "Troubleshooting", "Reference"),
  ("docs/migration.md", "Migration-Guide", "Reference"),
  ("docs/test-coverage.md", "Test-Coverage", "Development"),
]
# Generated pages that have no markdown source, with their sidebar section.
GENERATED_PAGES: list[tuple[str, str]] = [("Mise-Tasks", "Reference"), ("API-Reference", "Reference")]
SECTIONS = ["User Guide", "Running the Daemon", "Reference", "Development"]
OPENAPI_SOURCE = "docs/openapi.yaml"
# Pages the wiki keeps that this script does not own.
UNMANAGED_OK = {"_Footer.md", "_Sidebar.md"}

_LINK_RE = re.compile(r"(!?)\[((?:[^\[\]]|\[[^\[\]]*\])*)\]\(([^)\s]+)((?:\s+\"[^\"]*\")?)\)")
_FENCE_RE = re.compile(r"^\s*(```|~~~)")
_MISE_HEADER_RE = re.compile(r"^#MISE\s+(description|aliases)\s*=\s*(.+)$")


@dataclass
class Task:
  name: str
  aliases: list[str]
  description: str


def repo_slug(root: Path = ROOT) -> str:
  """``owner/repo`` from the origin remote (https or ssh), or the default."""
  try:
    url = subprocess.run(["git", "-C", str(root), "remote", "get-url", "origin"], capture_output=True, text=True, check=True).stdout.strip()
  except (OSError, subprocess.CalledProcessError):
    return DEFAULT_SLUG
  match = re.search(r"github\.com[:/]([^/]+/[^/]+?)(?:\.git)?$", url)
  return match.group(1) if match else DEFAULT_SLUG


def _generated_note(source: str) -> str:
  return "<!-- Generated by `mise run wiki:build` from %s. Edit the source in the main repository, not this page. -->" % source


def rewrite_links(text: str, source: str, slug: str, root: Path = ROOT, ref: str = DEFAULT_REF, unresolved: list | None = None) -> str:
  """Rewrite relative markdown links in *text* (from repo file *source*) for the wiki.

  Unresolvable relative targets are left as-is and appended to *unresolved*.
  """
  pages_by_source = {src: page for src, page, _ in PAGES}
  pages_by_source[OPENAPI_SOURCE] = "API-Reference"
  base_dir = posixpath.dirname(source)

  def _replace(match: re.Match) -> str:
    bang, label, target, title = match.groups()
    if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith("#"):
      return match.group(0)
    path, _, anchor = target.partition("#")
    resolved = posixpath.normpath(posixpath.join(base_dir, path))
    suffix = "#" + anchor if anchor else ""
    if resolved in pages_by_source:
      new = pages_by_source[resolved] + suffix
    elif (root / resolved).exists() and not resolved.startswith(".."):
      if bang:
        new = "https://raw.githubusercontent.com/%s/%s/%s" % (slug, ref, resolved)
      else:
        kind = "tree" if (root / resolved).is_dir() else "blob"
        new = "https://github.com/%s/%s/%s/%s%s" % (slug, kind, ref, resolved, suffix)
    else:
      if unresolved is not None:
        unresolved.append("%s: %s" % (source, target))
      return match.group(0)
    return "%s[%s](%s%s)" % (bang, label, new, title)

  out = []
  in_fence = False
  for line in text.split("\n"):
    if _FENCE_RE.match(line):
      in_fence = not in_fence
      out.append(line)
      continue
    out.append(line if in_fence else _LINK_RE.sub(_replace, line))
  return "\n".join(out)


def mise_tasks(root: Path = ROOT) -> list[Task]:
  """Tasks defined under ``.mise/tasks`` with their ``#MISE`` description and aliases."""
  tasks_dir = root / ".mise" / "tasks"
  tasks = []
  for path in sorted(tasks_dir.rglob("*")):
    if not path.is_file() or path.name.startswith("."):
      continue
    description, aliases = "", []
    with open(path, encoding="utf-8", errors="replace") as f:
      for _ in range(10):
        line = f.readline()
        if not line:
          break
        match = _MISE_HEADER_RE.match(line.strip())
        if not match:
          continue
        key, value = match.groups()
        try:
          parsed = json.loads(value)
        except ValueError:
          parsed = value.strip("\"'")
        if key == "description":
          description = str(parsed)
        else:
          aliases = [str(a) for a in parsed] if isinstance(parsed, list) else [str(parsed)]
    if not description:
      continue
    name = ":".join(path.relative_to(tasks_dir).parts)
    tasks.append(Task(name, aliases, description))
  return tasks


def task_names(root: Path = ROOT) -> set[str]:
  """Every runnable task name and alias."""
  names = set()
  for task in mise_tasks(root):
    names.add(task.name)
    names.update(task.aliases)
  return names


def _cell(text: str) -> str:
  return text.replace("|", "\\|")


def render_mise_tasks(tasks: list[Task]) -> str:
  lines = [
    _generated_note(".mise/tasks/"),
    "",
    "# Mise Tasks",
    "",
    "All `mise run` tasks in the project, generated from each task's `#MISE description`.",
    "Run `mise tasks` to list them locally.",
    "",
    "Install [mise](https://mise.jdx.dev/) with `curl https://mise.run | sh`, then run `mise install` once in the",
    "repository root to activate the pinned tools.",
  ]
  groups: dict[str, list[Task]] = {}
  for task in tasks:
    groups.setdefault(task.name.split(":", 1)[0], []).append(task)
  for group in sorted(groups):
    lines += ["", "## %s" % group, "", "| Task | Aliases | Description |", "| --- | --- | --- |"]
    for task in groups[group]:
      aliases = ", ".join("`%s`" % a for a in task.aliases)
      lines.append("| `mise run %s` | %s | %s |" % (task.name, aliases, _cell(task.description)))
  return "\n".join(lines) + "\n"


def render_api_reference(spec: str) -> str:
  return "\n".join(
    [
      _generated_note(OPENAPI_SOURCE),
      "",
      "# API Reference",
      "",
      "The SMA-NG daemon's OpenAPI 3.1 specification. The endpoints, authentication and request formats are",
      "described in [Daemon Mode](Daemon-Mode); a running daemon also serves its own docs at `/docs`.",
      "",
      "```yaml",
      spec.rstrip("\n"),
      "```",
      "",
    ]
  )


def render_sidebar() -> str:
  lines = ["# SMA-NG", "", "- [Home](Home)", "", "---"]
  for section in SECTIONS:
    entries = [page for _, page, sec in PAGES if sec == section] + [page for page, sec in GENERATED_PAGES if sec == section]
    if not entries:
      continue
    lines += ["", "## %s" % section, ""]
    lines += ["- [%s](%s)" % (page.replace("-", " "), page) for page in entries]
  return "\n".join(lines) + "\n"


def render_footer(slug: str) -> str:
  return "# Footer\n\n---\n[SMA-NG](https://github.com/%s) · [Docs](Home) · [Issues](https://github.com/%s/issues)\n" % (slug, slug)


def render_pages(root: Path = ROOT, slug: str | None = None, unresolved: list | None = None) -> dict[str, str]:
  """Map of wiki filename -> content for every managed page."""
  slug = slug or repo_slug(root)
  pages = {}
  for source, page, _ in PAGES:
    text = (root / source).read_text(encoding="utf-8")
    pages[page + ".md"] = _generated_note(source) + "\n\n" + rewrite_links(text, source, slug, root, unresolved=unresolved)
  pages["API-Reference.md"] = render_api_reference((root / OPENAPI_SOURCE).read_text(encoding="utf-8"))
  pages["Mise-Tasks.md"] = render_mise_tasks(mise_tasks(root))
  pages["_Sidebar.md"] = render_sidebar()
  pages["_Footer.md"] = render_footer(slug)
  return pages


def unmapped_docs(root: Path = ROOT) -> list[str]:
  """Top-level ``docs/*.md`` files that have no wiki page (so new docs aren't silently skipped)."""
  mapped = {src for src, _, _ in PAGES}
  return sorted(str(p.relative_to(root)) for p in (root / "docs").glob("*.md") if str(p.relative_to(root)) not in mapped)


def build(out: Path, root: Path = ROOT, prune: bool = False) -> int:
  out.mkdir(parents=True, exist_ok=True)
  pages = render_pages(root)
  for name, content in pages.items():
    (out / name).write_text(content, encoding="utf-8")
  extra = sorted(p.name for p in out.glob("*.md") if p.name not in pages and p.name not in UNMANAGED_OK)
  for name in extra:
    if prune:
      (out / name).unlink()
      print("pruned: %s" % name)
    else:
      print("unmanaged page kept (use --prune to remove): %s" % name)
  print("wrote %d wiki pages to %s" % (len(pages), out))
  return 0


def check(root: Path = ROOT) -> int:
  """Fail when a doc has no wiki mapping or a relative link cannot be resolved."""
  problems = ["no wiki page mapping for %s (add it to PAGES in scripts/wiki_sync.py)" % d for d in unmapped_docs(root)]
  unresolved: list[str] = []
  render_pages(root, slug=DEFAULT_SLUG, unresolved=unresolved)
  problems += ["unresolved link %s" % u for u in unresolved]
  for problem in problems:
    print(problem, file=sys.stderr)
  if not problems:
    print("wiki check: %d pages render, all links resolve" % (len(PAGES) + 4))
  return 1 if problems else 0


def main(argv: list[str] | None = None) -> int:
  parser = argparse.ArgumentParser(description="Generate the GitHub wiki from docs/")
  sub = parser.add_subparsers(dest="cmd", required=True)
  b = sub.add_parser("build", help="Write wiki pages into a wiki checkout")
  b.add_argument("--out", required=True, help="Wiki checkout directory")
  b.add_argument("--prune", action="store_true", help="Delete wiki pages this script does not generate")
  sub.add_parser("check", help="Verify every doc maps to a page and every relative link resolves")
  args = parser.parse_args(argv)
  if args.cmd == "build":
    return build(Path(os.path.expanduser(args.out)), prune=args.prune)
  return check()


if __name__ == "__main__":
  sys.exit(main())
